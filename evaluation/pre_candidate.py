def predict_from_model(
    model_path,
    tadf_data_dir,
    env_data_dir,
    orig_csv_path,
    target_env,
    output_csv_path,
    batch_size=100,
):
    """
    Load model and data for prediction against ONE environment.
    Includes reverse normalization to recover true physical values.
    """
    use_cuda = torch.cuda.is_available()
    device = torch.device("cuda:0" if use_cuda else "cpu")
    torch.set_num_threads(10 if use_cuda else 20)
    print(f"\nUsing device: {device}")

    scaler_dict = load_scaler_dict(Path(orig_csv_path))

    print(f"\nLoading model from: {model_path}")
    if not Path(model_path).exists():
        print(f"ERROR: Model file does not exist: {model_path}")
        return

    model = torch.load(model_path, map_location=device)
    model.to(device)
    model.eval()

    tadf_atom_file = Path(tadf_data_dir) / "tadf_atom_features.pkl"
    try:
        with open(tadf_atom_file, "rb") as f:
            num_tadf_molecules = len(pickle.load(f))
    except FileNotFoundError:
        print(f"ERROR: Could not find {tadf_atom_file}. Did you run graph conversion?")
        return

    env_key, env_idx, display_env_name = target_env

    print(
        f"Found {num_tadf_molecules} TADF molecules. "
        f"Will predict environment: {display_env_name} (index: {env_idx})."
    )

    print("\n" + "=" * 50)
    print(f"Processing environment: '{display_env_name}' (index: {env_idx})")
    print("=" * 50)

    temp_env_dir = TEMP_ENV_ROOT / f"temp_env_{env_idx}"
    temp_env_dir.mkdir(parents=True, exist_ok=True)

    try:
        if env_idx == -1:
            print("Pure solid selected. Copying TADF graphs as environment graphs.")
            file_mapping = {
                "tadf_edge_index.pkl": "env_edge_index.pkl",
                "tadf_edge_attr.pkl": "env_edge_attr.pkl",
                "tadf_rev_edge_index.pkl": "env_rev_edge_index.pkl",
                "tadf_atom_features.pkl": "env_atom_features.pkl",
            }
            for tadf_file, env_file in file_mapping.items():
                src_path = Path(tadf_data_dir) / tadf_file
                dst_path = temp_env_dir / env_file
                shutil.copy(src_path, dst_path)

        else:
            print("Broadcasting solvent/host data to match TADF molecules.")
            env_files = [
                "env_edge_index.pkl",
                "env_edge_attr.pkl",
                "env_rev_edge_index.pkl",
                "env_atom_features.pkl",
            ]
            for pkl_file in env_files:
                orig_path = Path(env_data_dir) / pkl_file
                with open(orig_path, "rb") as f:
                    all_env_data = pickle.load(f)

                single_env_data = all_env_data[env_idx]
                duplicated_data = [single_env_data] * num_tadf_molecules

                temp_path = temp_env_dir / pkl_file
                with open(temp_path, "wb") as f:
                    pickle.dump(duplicated_data, f)

        dataset = load_pre_data.MoleculeDataset(
            str(Path(tadf_data_dir) / "tadf_edge_index.pkl"),
            str(Path(tadf_data_dir) / "tadf_edge_attr.pkl"),
            str(Path(tadf_data_dir) / "tadf_rev_edge_index.pkl"),
            str(Path(tadf_data_dir) / "tadf_atom_features.pkl"),
            str(temp_env_dir / "env_edge_index.pkl"),
            str(temp_env_dir / "env_edge_attr.pkl"),
            str(temp_env_dir / "env_rev_edge_index.pkl"),
            str(temp_env_dir / "env_atom_features.pkl"),
        )

        test_loader = DataLoader(
            dataset,
            batch_size=batch_size,
            shuffle=False,
            drop_last=False,
            num_workers=2,
            collate_fn=load_pre_data.collate_fn,
            pin_memory=True,
        )

        preds_list = []
        inference_epoch = 200

        print("Starting inference for current environment.")
        with torch.no_grad():
            for _, batch_data in tqdm(enumerate(test_loader), total=len(test_loader)):
                tadf_data = batch_data[0].to(device)
                host_data = batch_data[1].to(device)

                props_pre = model(tadf_data, host_data, inference_epoch)
                batch_preds = props_pre.cpu().detach().numpy()
                preds_list.append(batch_preds)

                del tadf_data, host_data, props_pre
                if torch.cuda.is_available():
                    torch.cuda.empty_cache()

        all_preds = np.vstack(preds_list)
        properties = [
            "Pred_absorption_nm",
            "Pred_emission_nm",
            "Pred_Delta_EST_eV",
            "Pred_PLQY_percent",
        ]

        result_df = pd.DataFrame(all_preds, columns=properties)
        result_df.insert(0, "ID", range(1, len(result_df) + 1))
        result_df.insert(1, "Target_Environment", display_env_name)

        if scaler_dict:
            for pred_col in properties:
                if pred_col in scaler_dict:
                    min_v = scaler_dict[pred_col]["min"]
                    max_v = scaler_dict[pred_col]["max"]
                    real_col_name = pred_col.replace("Pred_", "Transform_")
                    result_df[real_col_name] = (
                        result_df[pred_col] * (max_v - min_v) + min_v
                    )

        output_csv_path = Path(output_csv_path)
        output_csv_path.parent.mkdir(parents=True, exist_ok=True)
        result_df.to_csv(output_csv_path, index=False)

        print("\n" + "=" * 50)
        print(f"Prediction completed. Results saved to: {output_csv_path}")
        print("=" * 50)

    finally:
        if temp_env_dir.exists():
            shutil.rmtree(temp_env_dir)
            print("Cleaned up temporary environment files.")

        if "dataset" in locals():
            del dataset
        if "test_loader" in locals():
            del test_loader
        gc.collect()


