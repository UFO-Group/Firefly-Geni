def ask_single_env(default_env: str = "toluene"):
    """Ask the user to input exactly one environment."""
    while True:
        text = input(f"\nEnter one target environment [default: {default_env}]: ").strip()

        if text == "":
            text = default_env

        if "," in text or "，" in text:
            print("Only one environment can be selected at a time.")
            print("Please enter a single index or a single environment name.")
            continue

        env_key = text.lower().strip()

        if env_key not in ENV_MAPPING:
            print(f"Environment '{text}' was not found in ENV_MAPPING. Please try again.")
            continue

        env_idx = ENV_MAPPING[env_key]
        env_name = INDEX_TO_NAME[env_idx]
        return env_key, env_idx, env_name


def ask_int(prompt: str, default: int, min_value: int = None) -> int:
    """Ask for an integer with a default value."""
    while True:
        text = input(f"{prompt} [default: {default}]: ").strip()

        if text == "":
            return default

        try:
            value = int(text)
        except ValueError:
            print("Invalid input. Please enter an integer.")
            continue

        if min_value is not None and value < min_value:
            print(f"Value must be >= {min_value}.")
            continue

        return value


def safe_filename_name(name: str) -> str:
    """Convert an environment name into a filename-safe tag."""
    name = str(name).strip().lower()
    name = name.replace(" ", "_")
    name = re.sub(r"[^a-zA-Z0-9_\-]+", "_", name)
    name = re.sub(r"_+", "_", name).strip("_")
    return name if name else "environment"


def load_scaler_dict(orig_csv_path: Path):
    """Read original dataset and extract min/max values for reverse normalization."""
    print(f"\nReading the original dataset for normalization parameters: {orig_csv_path}")

    scaler_dict = {}
    column_mapping = {
        "Pred_absorption_nm": "absorption_wavelength_nm",
        "Pred_emission_nm": "emission_wavelength_nm",
        "Pred_Delta_EST_eV": "Delta_EST_eV",
        "Pred_PLQY_percent": "PLQY_percent",
    }

    if not orig_csv_path.exists():
        print(f"WARNING: Original dataset not found: {orig_csv_path}")
        print("Physical-value recovery will be unavailable.")
        return scaler_dict

    df_orig = pd.read_csv(orig_csv_path)
    for pred_col, orig_col in column_mapping.items():
        if orig_col in df_orig.columns:
            valid_values = df_orig[orig_col].dropna().values
            scaler_dict[pred_col] = {
                "min": np.min(valid_values),
                "max": np.max(valid_values),
            }

    print("Normalization parameters were extracted successfully.")
    return scaler_dict


