def require_file(path: Path, label: str) -> None:
    """Raise an explicit error if a required file does not exist."""
    if not path.exists():
        raise FileNotFoundError(f"{label} not found: {path}")


def require_dir(path: Path, label: str) -> None:
    """Raise an explicit error if a required directory does not exist."""
    if not path.exists():
        raise FileNotFoundError(f"{label} not found: {path}")
    if not path.is_dir():
        raise NotADirectoryError(f"{label} is not a directory: {path}")


def get_model_path() -> Path:
    """Return the preferred model path, using fallback only if needed."""
    if MODEL_PATH.exists():
        return MODEL_PATH
    if MODEL_PATH_FALLBACK.exists():
        print(f"WARNING: Preferred model file not found: {MODEL_PATH}")
        print(f"Using fallback model file: {MODEL_PATH_FALLBACK}")
        return MODEL_PATH_FALLBACK
    raise FileNotFoundError(
        "Model file not found. Checked:\n"
        f"  {MODEL_PATH}\n"
        f"  {MODEL_PATH_FALLBACK}"
    )


def env_required_files_exist(env_data_dir: Path) -> bool:
    """Check whether an environment graph directory has all required pkl files."""
    required = [
        "env_edge_index.pkl",
        "env_edge_attr.pkl",
        "env_rev_edge_index.pkl",
        "env_atom_features.pkl",
    ]
    return all((env_data_dir / name).exists() for name in required)


def get_env_data_dir() -> Path:
    """Find the environment graph pkl directory."""
    for candidate in ENV_DATA_DIR_CANDIDATES:
        if candidate.exists() and env_required_files_exist(candidate):
            return candidate

    checked = "\n".join(str(path) for path in ENV_DATA_DIR_CANDIDATES)
    raise FileNotFoundError(
        "Environment graph pkl files were not found. Checked:\n"
        f"{checked}\n"
        "Required files: env_edge_index.pkl, env_edge_attr.pkl, "
        "env_rev_edge_index.pkl, env_atom_features.pkl"
    )


def check_tadf_graph_files(tadf_data_dir: Path) -> None:
    """Check candidate TADF graph pkl files."""
